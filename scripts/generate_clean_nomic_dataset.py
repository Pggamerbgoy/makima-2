def save_and_verify():
    data = get_clean_dataset()
    out_json = Path(__file__).resolve().parent / "clean_nomic_training_data.json"
    
    formatted = [
        {"id": i + 1, "user_utterance": text, "target_domain": label}
        for i, (text, label) in enumerate(data)
    ]
    
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(formatted, f, indent=2, ensure_ascii=False)
        
    print(f"Generated {len(formatted)} verified training samples.")
    print(f"Saved to: {out_json}")


if __name__ == "__main__":
    save_and_verify()
